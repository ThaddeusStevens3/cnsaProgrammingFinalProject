USE XYZINC

CREATE TABLE PRESCRIPTION(
	PRESCRIPTION_ID    VARCHAR(7) NOT NULL
	CONSTRAINT    PK_PRESCRIPTION_ID PRIMARY KEY,

	PATIENT_ID    VARCHAR(7) NOT NULL FOREIGN KEY (PATIENT_ID) REFERENCES PATIENT(PATIENT_ID),

	PRESCRIPTION_NAME	VARCHAR(25) NOT NULL,
	CONSUMPTION_METHOD	VARCHAR(25) NOT NULL,
	REFILL_NUMBER VARCHAR(25),

	PRESCRIPTION_DATE DATE NOT NULL,

	)